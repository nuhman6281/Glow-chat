export function EmojiPicker({
  onEmojiSelect,
  className,
  children,
  open: controlledOpen,
  onOpenChange,
}: EmojiPickerProps) {
  const [searchTerm, setSearchTerm] = useState("");
  const [activeTab, setActiveTab] = useState("recent");
  const [open, setOpen] = useState(false);

  const isControlled = controlledOpen !== undefined;
  const isOpen = isControlled ? controlledOpen : open;
  const setPopoverOpen = isControlled ? onOpenChange! : setOpen;

  const filteredEmojis = useMemo(() => {
    if (!searchTerm)
      return EMOJI_DATA[activeTab as keyof typeof EMOJI_DATA] || [];

    const allEmojis = Object.values(EMOJI_DATA).flat();
    return allEmojis.filter(
      (emoji) =>
        emoji.includes(searchTerm) ||
        emoji.charCodeAt(0).toString(16).includes(searchTerm.toLowerCase()),
    );
  }, [searchTerm, activeTab]);

  const handleEmojiClick = (emoji: string) => {
    onEmojiSelect(emoji);
    setPopoverOpen(false);
  };

  return (
    <Popover open={isOpen} onOpenChange={setPopoverOpen}>
      <PopoverTrigger asChild>{children}</PopoverTrigger>
      <PopoverContent className={cn("w-80 p-0", className)} align="end">
        {/* Search */}
        <div className="p-3 border-b">
          <div className="relative">
            <Search className="absolute left-3 top-1/2 transform -translate-y-1/2 h-4 w-4 text-muted-foreground" />
            <Input
              placeholder="Search emojis..."
              value={searchTerm}
              onChange={(e) => setSearchTerm(e.target.value)}
              className="pl-9"
            />
          </div>
        </div>

        {/* Tabs */}
        <Tabs value={activeTab} onValueChange={setActiveTab} className="w-full">
          <TabsList className="grid w-full grid-cols-5 h-12">
            {Object.entries(EMOJI_CATEGORIES)
              .slice(0, 5)
              .map(([key, { icon: Icon, label }]) => (
                <TabsTrigger key={key} value={key} className="text-xs">
                  <Icon className="h-4 w-4" />
                </TabsTrigger>
              ))}
          </TabsList>

          <ScrollArea className="h-64">
            <TabsContent value={activeTab} className="p-3">
              <div className="grid grid-cols-8 gap-1">
                {filteredEmojis.map((emoji, index) => (
                  <Button
                    key={`${emoji}-${index}`}
                    variant="ghost"
                    size="sm"
                    className="h-8 w-8 p-0 text-lg hover:bg-muted"
                    onClick={() => handleEmojiClick(emoji)}
                  >
                    {emoji}
                  </Button>
                ))}
              </div>
            </TabsContent>
          </ScrollArea>
        </Tabs>
      </PopoverContent>
    </Popover>
  );
}
